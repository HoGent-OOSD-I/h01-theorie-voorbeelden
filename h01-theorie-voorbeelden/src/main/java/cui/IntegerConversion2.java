package cui;

public class IntegerConversion2
{
	public static void main(String args[])
	{
		int getal = 26; // <1>

		System.out.printf("%d%n", getal);
		System.out.printf("%o%n", getal);
		System.out.printf("%x%n", getal);
		System.out.printf("%X%n", getal);
	} // end main
} // end class IntegerConversion2
